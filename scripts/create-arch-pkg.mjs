import { execSync } from 'node:child_process';
import { readFileSync, mkdirSync, writeFileSync, rmSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';

const tauriConfig = JSON.parse(readFileSync('src-tauri/tauri.conf.json', 'utf8'));
const productName = tauriConfig.productName || 'HK UMKM';
const version = process.argv[2] || JSON.parse(readFileSync('package.json', 'utf8')).version;

const pkgName = 'hk-umkm';
const arch    = 'x86_64';

// Read actual binary name from Cargo.toml (first [[bin]] name or package name)
const cargoToml = readFileSync('src-tauri/Cargo.toml', 'utf8');
const binNameMatch = cargoToml.match(/^\[\[bin\]\][\s\S]*?^name\s*=\s*"([^"]+)"/m)
  || cargoToml.match(/^name\s*=\s*"([^"]+)"/m);
const cargoBinaryName = binNameMatch ? binNameMatch[1] : 'app';
console.log(`Detected Cargo binary name: ${cargoBinaryName}`);
// e.g. "HK.UMKM-0.20.2-x86_64.pkg.tar.zst"
const pkgFileName = `${productName.replace(/\s+/g, '.')}-${version}-${arch}.pkg.tar.zst`;

console.log(`Building Arch Linux package: ${pkgFileName}...`);

const stageDir = path.resolve(`.pkg_stage_${Date.now()}`);
if (existsSync(stageDir)) rmSync(stageDir, { recursive: true, force: true });

mkdirSync(path.join(stageDir, 'usr/bin'), { recursive: true });
mkdirSync(path.join(stageDir, 'usr/share/applications'), { recursive: true });
mkdirSync(path.join(stageDir, 'usr/share/icons/hicolor/128x128/apps'), { recursive: true });
mkdirSync(path.join(stageDir, 'usr/share/icons/hicolor/32x32/apps'), { recursive: true });

// Copy binary — Cargo binary is named after Cargo.toml 'name', install it as pkgName
const srcBinary = `src-tauri/target/release/${cargoBinaryName}`;
if (!existsSync(srcBinary)) {
  // Fallback: list release dir to help debug
  const releaseFiles = readdirSync('src-tauri/target/release').filter(f => !f.includes('.'));
  console.error(`Binary not found: ${srcBinary}`);
  console.error(`Executables in release dir: ${releaseFiles.join(', ')}`);
  process.exit(1);
}
execSync(`cp "${srcBinary}" "${stageDir}/usr/bin/${pkgName}"`);
execSync(`chmod 755 "${stageDir}/usr/bin/${pkgName}"`);

// Desktop entry
const desktopContent = `[Desktop Entry]
Name=${productName}
Comment=HK UMKM Application
Exec=${pkgName}
Icon=${pkgName}
Terminal=false
Type=Application
Categories=Office;Finance;Utility;
`;
writeFileSync(path.join(stageDir, `usr/share/applications/${pkgName}.desktop`), desktopContent);

// Icons
if (existsSync('src-tauri/icons/128x128.png')) {
  execSync(`cp "src-tauri/icons/128x128.png" "${stageDir}/usr/share/icons/hicolor/128x128/apps/${pkgName}.png"`);
}
if (existsSync('src-tauri/icons/32x32.png')) {
  execSync(`cp "src-tauri/icons/32x32.png" "${stageDir}/usr/share/icons/hicolor/32x32/apps/${pkgName}.png"`);
}

// Calculate installed size
const binarySize = readFileSync(path.join(stageDir, `usr/bin/${pkgName}`)).length;

// .PKGINFO
const pkgInfoContent = `# Generated by create-arch-pkg
pkgname = ${pkgName}
pkgbase = ${pkgName}
pkgver = ${version}-1
pkgdesc = HK UMKM Application
url = https://github.com/HeriEfendi/HK_UMKM
builddate = ${Math.floor(Date.now() / 1000)}
packager = Release Bot <noreply@github.com>
size = ${binarySize}
arch = ${arch}
license = MIT
depend = webkit2gtk-4.1
depend = gtk3
depend = cairo
depend = hicolor-icon-theme
depend = openssl
provides = ${pkgName}
conflicts = ${pkgName}
`;
writeFileSync(path.join(stageDir, '.PKGINFO'), pkgInfoContent);

// Pack with zstd (installed via apt on Ubuntu runner)
execSync(
  `tar -c --owner=root --group=root -C "${stageDir}" .PKGINFO usr | zstd -3 -o "${pkgFileName}"`,
  { stdio: 'inherit' }
);

// Cleanup
rmSync(stageDir, { recursive: true, force: true });

console.log(`Successfully created Arch Linux package: ${pkgFileName}`);
